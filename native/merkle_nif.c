static ERL_NIF_TERM nif_fp_query_gemv_indexed(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    int dim_int;
    ErlNifUInt64 count, dim;

    if (!enif_get_uint64(env, argv[3], &count)) return enif_make_badarg(env);
    if (!enif_get_uint64(env, argv[4], &dim)) return enif_make_badarg(env);

    if (!enif_get_tuple(env, argv[0], &dim_int, NULL)) return enif_make_badarg(env);
    if ((size_t)dim_int != dim) return enif_make_badarg(env);

    ErlNifBinary query_bin;
    if (!enif_inspect_binary(env, argv[1], &query_bin)) return enif_make_badarg(env);
    if (query_bin.size != dim * 8) return enif_make_badarg(env);

    ErlNifBinary indices_bin;
    if (!enif_inspect_binary(env, argv[2], &indices_bin)) return enif_make_badarg(env);
    size_t num_indices = indices_bin.size / 4;

    const double** columns = malloc(dim * sizeof(double*));
    if (!columns) return enif_make_badarg(env);

    const ERL_NIF_TERM* tuple_elements;
    if (!enif_get_tuple(env, argv[0], &dim_int, &tuple_elements)) {
        free(columns);
        return enif_make_badarg(env);
    }

    ErlNifBinary* col_bins = malloc(dim * sizeof(ErlNifBinary));
    if (!col_bins) {
        free(columns);
        return enif_make_badarg(env);
    }

    for (size_t d = 0; d < dim; d++) {
        if (!enif_inspect_binary(env, tuple_elements[d], &col_bins[d])) {
            free(columns);
            free(col_bins);
            return enif_make_badarg(env);
        }
        if (col_bins[d].size != count * 8) {
            free(columns);
            free(col_bins);
            return enif_make_badarg(env);
        }
        columns[d] = (const double*)col_bins[d].data;
    }

    ErlNifBinary scores_bin;
    if (!enif_alloc_binary(num_indices * 8, &scores_bin)) {
        free(columns);
        free(col_bins);
        return enif_make_badarg(env);
    }

    fp_query_gemv_indexed_f64(
        columns,
        (const double*)query_bin.data,
        (const int32_t*)indices_bin.data,
        num_indices,
        (double*)scores_bin.data,
        count,
        dim
    );

    free(columns);
    free(col_bins);

    return enif_make_binary(env, &scores_bin);
}

static ERL_NIF_TERM nif_fp_query_topk(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifBinary scores_bin;
    ErlNifUInt64 count, k;
    double threshold;

    if (!enif_inspect_binary(env, argv[0], &scores_bin)) return enif_make_badarg(env);
    if (!enif_get_uint64(env, argv[1], &count)) return enif_make_badarg(env);
    if (!enif_get_uint64(env, argv[2], &k)) return enif_make_badarg(env);
    if (!enif_get_double(env, argv[3], &threshold)) return enif_make_badarg(env);

    if (scores_bin.size != count * 8) return enif_make_badarg(env);

    ErlNifBinary indices_bin, result_scores_bin;
    if (!enif_alloc_binary(k * 4, &indices_bin)) return enif_make_badarg(env);
    if (!enif_alloc_binary(k * 8, &result_scores_bin)) {
        enif_release_binary(&indices_bin);
        return enif_make_badarg(env);
    }

    size_t result_count = fp_query_topk_f64(
        (const double*)scores_bin.data,
        count,
        k,
        threshold,
        (int32_t*)indices_bin.data,
        (double*)result_scores_bin.data
    );

    if (result_count < k) {
        enif_realloc_binary(&indices_bin, result_count * 4);
        enif_realloc_binary(&result_scores_bin, result_count * 8);
    }

    return enif_make_tuple3(env,
        enif_make_uint64(env, result_count),
        enif_make_binary(env, &indices_bin),
        enif_make_binary(env, &result_scores_bin)
    );
}

