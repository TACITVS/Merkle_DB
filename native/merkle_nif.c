static ERL_NIF_TERM nif_fp_hnsw_insert(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    hnsw_res* res;
    int vector_idx;
    ErlNifBinary vec_bin;
    ErlNifUInt64 db_count;

    if (!enif_get_resource(env, argv[0], HNSW_RES_TYPE, (void**)&res)) return enif_make_badarg(env);
    if (!enif_get_int(env, argv[1], &vector_idx)) return enif_make_badarg(env);
    if (!enif_inspect_binary(env, argv[2], &vec_bin)) return enif_make_badarg(env);
    if (!enif_get_uint64(env, argv[4], &db_count)) return enif_make_badarg(env);

    int dim = res->index->dim;
    if (vec_bin.size != (size_t)dim * 8) return enif_make_badarg(env);

    const double** columns = malloc(dim * sizeof(double*));
    if (!columns) return enif_make_badarg(env);

    int dim_int;
    const ERL_NIF_TERM* tuple_elements;
    if (!enif_get_tuple(env, argv[3], &dim_int, &tuple_elements) || dim_int != dim) {
        free(columns);
        return enif_make_badarg(env);
    }
    
    ErlNifBinary* col_bins = malloc(dim * sizeof(ErlNifBinary));
    if (!col_bins) {
        free(columns);
        return enif_make_badarg(env);
    }

    double** converted_columns = NULL;

    for (int d = 0; d < dim; d++) {
        if (!enif_inspect_binary(env, tuple_elements[d], &col_bins[d])) {
            // Free everything before returning
            if (converted_columns) {
                for (int j = 0; j < d; j++) if (converted_columns[j]) free(converted_columns[j]);
                free(converted_columns);
            }
            free(columns);
            free(col_bins);
            return enif_make_badarg(env);
        }

        if (col_bins[d].size == db_count * 4) {
            // f32 detected
            if (converted_columns == NULL) {
                converted_columns = calloc(dim, sizeof(double*));
                if (!converted_columns) { free(columns); free(col_bins); return enif_make_badarg(env); }
            }
            converted_columns[d] = malloc(db_count * sizeof(double));
            if (!converted_columns[d]) {
                for (int j = 0; j < d; j++) if (converted_columns[j]) free(converted_columns[j]);
                free(converted_columns); free(columns); free(col_bins); return enif_make_badarg(env);
            }
            float* src = (float*)col_bins[d].data;
            for (size_t i = 0; i < db_count; i++) {
                converted_columns[d][i] = (double)src[i];
            }
            columns[d] = converted_columns[d];
        } else if (col_bins[d].size == db_count * 8) {
            columns[d] = (const double*)col_bins[d].data;
        } else {
            if (converted_columns) {
                for (int j = 0; j < d; j++) if (converted_columns[j]) free(converted_columns[j]);
                free(converted_columns);
            }
            free(columns); free(col_bins); return enif_make_badarg(env);
        }
    }

    fp_hnsw_insert(res->index, vector_idx, (const double*)vec_bin.data, columns, (size_t)db_count);

    if (converted_columns) {
        for (int d = 0; d < dim; d++) {
            if (converted_columns[d]) free(converted_columns[d]);
        }
        free(converted_columns);
    }
    free(columns);
    free(col_bins);

    return enif_make_atom(env, "ok");
}

static ERL_NIF_TERM nif_fp_hnsw_search(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    hnsw_res* res;
    ErlNifBinary query_bin;
    int k, ef_search;
    ErlNifUInt64 db_count;

    if (!enif_get_resource(env, argv[0], HNSW_RES_TYPE, (void**)&res)) return enif_make_badarg(env);
    if (!enif_inspect_binary(env, argv[1], &query_bin)) return enif_make_badarg(env);
    if (!enif_get_int(env, argv[2], &k)) return enif_make_badarg(env);
    if (!enif_get_int(env, argv[3], &ef_search)) return enif_make_badarg(env);
    if (!enif_get_uint64(env, argv[5], &db_count)) return enif_make_badarg(env);

    int dim = res->index->dim;
    if (query_bin.size != (size_t)dim * 8) return enif_make_badarg(env);

    const double** columns = malloc(dim * sizeof(double*));
    if (!columns) return enif_make_badarg(env);

    int dim_int;
    const ERL_NIF_TERM* tuple_elements;
    if (!enif_get_tuple(env, argv[4], &dim_int, &tuple_elements) || dim_int != dim) {
        free(columns);
        return enif_make_badarg(env);
    }
    
    ErlNifBinary* col_bins = malloc(dim * sizeof(ErlNifBinary));
    if (!col_bins) {
        free(columns);
        return enif_make_badarg(env);
    }

    double** converted_columns = NULL;

    for (int d = 0; d < dim; d++) {
        if (!enif_inspect_binary(env, tuple_elements[d], &col_bins[d])) {
            if (converted_columns) {
                for (int j = 0; j < d; j++) if (converted_columns[j]) free(converted_columns[j]);
                free(converted_columns);
            }
            free(columns); free(col_bins); return enif_make_badarg(env);
        }

        if (col_bins[d].size == db_count * 4) {
            // f32 detected
            if (converted_columns == NULL) {
                converted_columns = calloc(dim, sizeof(double*));
                if (!converted_columns) { free(columns); free(col_bins); return enif_make_badarg(env); }
            }
            converted_columns[d] = malloc(db_count * sizeof(double));
            if (!converted_columns[d]) {
                for (int j = 0; j < d; j++) if (converted_columns[j]) free(converted_columns[j]);
                free(converted_columns); free(columns); free(col_bins); return enif_make_badarg(env);
            }
            float* src = (float*)col_bins[d].data;
            for (size_t i = 0; i < db_count; i++) {
                converted_columns[d][i] = (double)src[i];
            }
            columns[d] = converted_columns[d];
        } else if (col_bins[d].size == db_count * 8) {
            columns[d] = (const double*)col_bins[d].data;
        } else {
            if (converted_columns) {
                for (int j = 0; j < d; j++) if (converted_columns[j]) free(converted_columns[j]);
                free(converted_columns);
            }
            free(columns); free(col_bins); return enif_make_badarg(env);
        }
    }

    int32_t* results_indices = malloc(k * sizeof(int32_t));
    double* results_scores = malloc(k * sizeof(double));

    if (!results_indices || !results_scores) {
        if (results_indices) free(results_indices);
        if (results_scores) free(results_scores);
        if (converted_columns) {
            for (int d = 0; d < dim; d++) if (converted_columns[d]) free(converted_columns[d]);
            free(converted_columns);
        }
        free(columns); free(col_bins); return enif_make_badarg(env);
    }

    size_t result_count = fp_hnsw_search(
        res->index,
        (const double*)query_bin.data,
        k,
        ef_search,
        columns,
        (size_t)db_count,
        results_indices,
        results_scores
    );

    if (converted_columns) {
        for (int d = 0; d < dim; d++) {
            if (converted_columns[d]) free(converted_columns[d]);
        }
        free(converted_columns);
    }
    free(columns);
    free(col_bins);

    ErlNifBinary indices_bin, scores_bin;
    enif_alloc_binary(result_count * 4, &indices_bin);
    memcpy(indices_bin.data, results_indices, result_count * 4);
    
    enif_alloc_binary(result_count * 8, &scores_bin);
    memcpy(scores_bin.data, results_scores, result_count * 8);

    free(results_indices);
    free(results_scores);

    return enif_make_tuple3(env,
        enif_make_uint64(env, result_count),
        enif_make_binary(env, &indices_bin),
        enif_make_binary(env, &scores_bin)
    );
}

